CREATE INDEX idx_social_account_user_id
    ON social_account(user_id);



CREATE INDEX idx_tour_category_id
    ON tour(category_id);

CREATE INDEX idx_tour_image_tour_id
    ON tour_image(tour_id);

CREATE INDEX idx_tour_departure_tour_id
    ON tour_departure(tour_id);

CREATE INDEX idx_tour_place_tour_id
    ON tour_place(tour_id);

CREATE INDEX idx_tour_place_place_id
    ON tour_place(place_id);

CREATE INDEX idx_food_place_id
    ON food(place_id);

CREATE INDEX idx_booking_user_id
    ON booking(user_id);

CREATE INDEX idx_booking_departure_id
    ON booking(departure_id);

CREATE INDEX idx_booking_traveler_booking_id
    ON booking_traveler(booking_id);

CREATE INDEX idx_payment_booking_id
    ON payment(booking_id);



CREATE INDEX idx_review_image_review_id
    ON review_image(review_id);

CREATE INDEX idx_review_like_review_id
    ON review_like(review_id);

CREATE INDEX idx_review_like_user_id
    ON review_like(user_id);

CREATE INDEX idx_comment_review_id
    ON comments(review_id);

CREATE INDEX idx_comment_user_id
    ON comments(user_id);

CREATE INDEX idx_comment_parent_id
    ON comments(parent_comment_id);

CREATE INDEX idx_news_author_id
    ON news(author_id);